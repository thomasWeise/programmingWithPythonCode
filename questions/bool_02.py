"""Working with Boolean expressions."""

x1 = True
x2 = False

print(x1 and x2)                       # Line 6: What does it print?

print(not x1 or x2)                    # Line 8: What does it print?

print(not x1 and not x2)               # Line 10: What does it print?

print((x1 or x2) and (not x1 and x1))  # Line 12: What does it print?
