""" Print several results of rounding. """
print("==== -1.6 .. -1.4 ==== ")
print(round(-1.6))  # Line 3
print(round(-1.5))  # Line 4
print(round(-1.4))  # Line 5

print("==== -0.6 .. -0.4 ==== ")
print(round(-0.6))  # Line 8
print(round(-0.5))  # Line 9
print(round(-0.4))  # Line 10

print("==== 0.4 .. 0.6 ==== ")
print(round(0.4))  # Line 13
print(round(0.5))  # Line 14
print(round(0.6))  # Line 15

print("==== 1.4 .. 1.6 ==== ")
print(round(1.4))  # Line 18
print(round(1.5))  # Line 19
print(round(1.6))  # Line 20
